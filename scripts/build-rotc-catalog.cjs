#!/usr/bin/env node
'use strict';
// Writes data/rotc-ribbons.js, the list of JROTC and ROTC ribbons the picker offers, from the synced
// sheets in images/ribbons/military (their specs carry the name and the service).
//   node scripts/build-rotc-catalog.cjs
// CAPR 39-1 11.2.5: three JROTC/ROTC ribbons awarded by military departments may be worn after the CAP
// ribbons while the member is enrolled in the program; 11.2.1 puts them after the CAP awards and before
// foreign awards.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'images', 'ribbons', 'military');
const SERVICES = [
  { key: 'air-force-jrotc', label: 'Air Force JROTC' },
  { key: 'army-jrotc', label: 'Army JROTC' },
  { key: 'marine-corps-jrotc', label: 'Marine Corps JROTC' },
  { key: 'navy-jrotc', label: 'Navy JROTC' }
];
const PREFIX = 'mil-ribbon-rotc-';

const ribbons = [];
for(const file of fs.readdirSync(dir).filter(name => name.startsWith(PREFIX) && name.endsWith('.spec.json')).sort()){
  const spec = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const asset = spec.asset_id;
  const service = SERVICES.find(s => s.key === spec.service);
  if(!service) throw new Error(`${asset}: unknown service ${spec.service}`);
  // The art notes when a vendor page gave only a code; the picker shows the code.
  const name = String(spec.name).replace(/\s*\(name not given[^)]*\)\s*$/i, '').trim();
  ribbons.push({ id: 'rotc_' + asset.slice(PREFIX.length).replace(/-/g, '_'), asset, name, service: service.key });
}
ribbons.sort((a, b) => SERVICES.findIndex(s => s.key === a.service) - SERVICES.findIndex(s => s.key === b.service) || a.name.localeCompare(b.name));

const body = {
  limit: 3,
  ref: '11.2.5',
  services: SERVICES,
  ribbons
};
const out = `// The JROTC and ROTC ribbons the picker offers (CAPR 39-1 11.2.1, 11.2.5). Generated by
// scripts/build-rotc-catalog.cjs from the sheets in images/ribbons/military; do not edit by hand.
// id: 'rotc_' + the sheet's id after 'mil-ribbon-rotc-' with underscores; asset: the sheet's id.
(function(root, factory){
  const api = factory();
  if(typeof module === 'object' && module.exports) module.exports = api;
  if(root) root.CAPUBRotcRibbons = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function(){
  'use strict';
  const DATA = {
    limit: ${body.limit},
    ref: ${JSON.stringify(body.ref)},
    services: [
${body.services.map(s => '      ' + JSON.stringify(s)).join(',\n')}
    ],
    ribbons: [
${body.ribbons.map(r => '      ' + JSON.stringify(r)).join(',\n')}
    ]
  };
  const BY_ID = new Map(DATA.ribbons.map(r => [r.id, r]));
  return Object.assign({}, DATA, {
    isRotcRibbonId: id => BY_ID.has(String(id)),
    get: id => BY_ID.get(String(id)) || null
  });
});
`;
fs.writeFileSync(path.join(root, 'data', 'rotc-ribbons.js'), out);
console.log(`wrote data/rotc-ribbons.js (${ribbons.length} ribbons)`);
