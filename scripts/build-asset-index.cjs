#!/usr/bin/env node
// Writes data/asset-index.js: every artwork id in images/MANIFEST.json with its path, so the page
// can show gallery thumbnails without waiting for the manifest. Run after the manifest changes;
// tests/asset-index.test.cjs fails when the two disagree.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'data', 'asset-index.js');

function build(){
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'images', 'MANIFEST.json'), 'utf8'));
  const index = {};
  for(const a of manifest.assets || []) index[a.id] = a.path;
  const lines = Object.keys(index).sort().map(id => `  ${JSON.stringify(id)}: ${JSON.stringify(index[id])}`);
  return `// Generated by scripts/build-asset-index.cjs from images/MANIFEST.json. Do not edit by hand.
(function(root){
  const index = {
${lines.map(l => '  ' + l).join(',\n')}
  };
  if(typeof module === 'object' && module.exports) module.exports = index;
  else root.CAPUBAssetIndex = index;
})(typeof self !== 'undefined' ? self : this);
`;
}

if(require.main === module){
  fs.writeFileSync(OUT, build());
  console.log('wrote', path.relative(root, OUT));
}
module.exports = { build, OUT };
