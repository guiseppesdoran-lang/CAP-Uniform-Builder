'use strict';
// Writes the table of National Cadet Special Activities into member-report-rules.js from the list National Headquarters publishes ("Current and Past
// Special Activity Ribbon List": a page of activities down the side, fiscal years across the top, "Yes" where the activity was held).
//
//   node scripts/generate-ncsa-activity-list.cjs <list.pdf>           rewrite the block between the BEGIN and END marks of member-report-rules.js
//   node scripts/generate-ncsa-activity-list.cjs <list.pdf> --check   exit 1 when the block is not what the PDF gives
//
// A new edition of the list is a rerun. The PDF is data: it is read with the pdf.js the page ships (vendor/pdfjs), never run, and its path is an argument.
// What the list does not say is kept in the two tables below and nowhere else: the activities that are one credit however many places they are held in
// (FAMILIES), and the other names a row of a record may carry for the same activity (ALSO_NAMED: spellings the list gets wrong, past names, abbreviations).
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..');
const TARGET = path.join(ROOT, 'member-report-rules.js');
const BEGIN = '// BEGIN NCSA ACTIVITY LIST (generated by scripts/generate-ncsa-activity-list.cjs; do not edit by hand)';
const END = '// END NCSA ACTIVITY LIST';

// One credit per family per year: the places of one activity, as the importer has always counted them (a student row and a staff row, or two places
// of one academy, in one year). First match wins; an activity in no family is a family of its own, keyed by its printed name.
const FAMILIES = [
  ['PJOC', /Pararescue/i],
  ['NATIONAL FLIGHT ACADEMY', /^NFA\b/],
  ['HONOR GUARD ACADEMY', /Honor Guard Academy/i],
  ['SUPT FAMILIARIZATION COURSE', /Undergraduate Pilot Training/i],
  ['ENGINEERING TECHNOLOGIES ACADEMY', /^Engineering Technolog/i],
  ['HMRS', /^Hawk Mountain/i],
  ['CLA', /^Civic Leadership Academy/i],
  ['AFCEA', /Civil Engineering Academy/i],
  ['COS', /^Cadet Officer School/i],
  ['NATIONAL BLUE BERET', /^National Blue Beret/i],
  ['ADVANCED TECHNOLOGIES ACADEMY', /^Advanced Technolog/i]
];

// The list's spellings that are plain slips, corrected for matching (the printed name stays as printed).
const SLIPS = [[/Manufacuring/g, 'Manufacturing'], [/Acedemy/g, 'Academy'], [/Pacfic/g, 'Pacific']];

// Other names a record may use for an activity on the list. `when` is tested on the printed name. These are not from the list: they are the
// abbreviations and the names the importer already knew (js/member-report-import.js before the list was its table) for activities the list has.
const ALSO_NAMED = [
  [/Pararescue/i, ['PJOC', 'Pararescue Orientation Course']],
  [/^NFA\b/, ['NFA', 'National Flight Academy']],
  [/^National Blue Beret/i, ['NBB', 'Blue Beret']],
  [/^Hawk Mountain/i, ['HMRS', 'Hawk Mountain', 'Hawk Cadet Cadre']],
  [/^Civic Leadership Academy/i, ['CLA']],
  [/^Cadet Officer School/i, ['COS', 'Cadet Officers School']],
  [/Civil Engineering Academy/i, ['Air Force Civil Engineering Academy', 'Civil Engineering Academy', 'AFCEA']],
  [/Honor Guard Academy/i, ['Honor Guard Academy']],
  [/Undergraduate Pilot Training/i, ['SUPT', 'Specialized Undergraduate Pilot Training', 'Undergraduate Pilot Training']],
  [/^Advanced Technology Academy/i, ['Advanced Technologies Academy']],
  [/^Engineering Technologies Academy/i, ['Engineering Technology Academy']]
];

// Codes a record prints for an activity of the list, not yet ruled on, so empty: the importer counts a row given only by a code as it always did and tells
// the member which codes it counted. When the owner says what a code is, add one line: [code, the activity's name as the list prints it], for example
//   ['ABCD', 'Civic Leadership Academy'],
// and rerun this script: the code becomes one of that activity's other names, and its rows are credits of the list.
const CODE_NAMES = [
];

async function readList(pdfPath){
  const lib = path.join(ROOT, 'vendor', 'pdfjs');
  const ctx = { ReadableStream, WritableStream, TransformStream, structuredClone, console, setTimeout, clearTimeout, TextDecoder, TextEncoder, URL, Uint8Array, ArrayBuffer, Promise };
  ctx.window = ctx; ctx.self = ctx; ctx.globalThis = ctx;
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(lib, 'pdf.min.js'), 'utf8'), ctx);
  vm.runInContext(fs.readFileSync(path.join(lib, 'pdf.worker.min.js'), 'utf8'), ctx);
  ctx.pdfjsLib.GlobalWorkerOptions.workerSrc = 'pdf.worker.min.js';
  const doc = await ctx.pdfjsLib.getDocument({ data: new Uint8Array(fs.readFileSync(pdfPath)), isEvalSupported: false, disableFontFace: true, verbosity: 0 }).promise;
  const info = (await doc.getMetadata()).info || {};
  const items = [];
  for(let n = 1; n <= doc.numPages; n++){
    const content = await (await doc.getPage(n)).getTextContent();
    for(const it of content.items) if(it.str.trim()) items.push({ page: n, x: it.transform[4], y: Math.round(it.transform[5]), str: it.str.trim() });
  }
  await doc.destroy();
  // The year columns: the four-digit headings, each by its left edge; a "Yes" belongs to the nearest one.
  const columns = items.filter(it => /^20\d\d$/.test(it.str));
  if(!columns.length) throw new Error('No fiscal year headings found: the list has changed its layout.');
  const rows = new Map();
  for(const it of items){
    if(columns.includes(it)) continue;
    const key = `${it.page}:${it.y}`;
    if(!rows.has(key)) rows.set(key, []);
    rows.get(key).push(it);
  }
  const entries = [];
  for(const cells of rows.values()){
    const names = cells.filter(c => c.str !== 'Yes' && c.x < 100);
    const yes = cells.filter(c => c.str === 'Yes');
    if(!names.length || !yes.length) continue;
    const years = [...new Set(yes.map(c => Number(columns.reduce((best, col) => Math.abs(col.x - c.x) < Math.abs(best.x - c.x) ? col : best).str)))].sort((a, b) => b - a);
    entries.push({ name: names.map(c => c.str).join(' ').replace(/\s+/g, ' '), years });
  }
  if(!entries.length) throw new Error('No activity rows found: the list has changed its layout.');
  const created = /^D:(\d{4})(\d{2})(\d{2})/.exec(info.CreationDate || '');
  return { entries, newest: Math.max(...columns.map(c => Number(c.str))), oldest: Math.min(...columns.map(c => Number(c.str))), saved: created ? `${created[1]}-${created[2]}-${created[3]}` : 'a date the file does not give' };
}

function corrected(name){ return SLIPS.reduce((s, [re, to]) => s.replace(re, to), name); }
const q = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function build(list){
  const rows = list.entries.map(e => {
    const fixed = corrected(e.name);
    const others = [];
    const add = s => { if(s && s !== e.name && !others.includes(s)) others.push(s); };
    if(fixed !== e.name) add(fixed);
    const noParen = fixed.replace(/\s*\([^)]*\)/g, '').replace(/\s+/g, ' ').trim();
    add(noParen);
    // "Space Force Operations Academy – CO": the activity without the place that follows the dash.
    const bare = /^(.*\S)\s+[–-]\s+[A-Z]{2}$/.exec(noParen);
    if(bare) add(bare[1]);
    for(const [when, names] of ALSO_NAMED) if(when.test(fixed)) names.forEach(add);
    for(const [code, printed] of CODE_NAMES) if(printed === e.name) add(code);
    const family = FAMILIES.find(([, re]) => re.test(noParen));
    const activity = family ? family[0] : (bare ? bare[1] : noParen).toUpperCase();
    return { name: e.name, others, activity, current: e.years.includes(list.newest), years: e.years };
  }).sort((a, b) => a.name.localeCompare(b.name, 'en'));
  const lines = rows.map(r => `    {name:${q(r.name)},others:[${r.others.map(q).join(',')}],activity:${q(r.activity)},current:${r.current},years:[${r.years.join(',')}]}`);
  return [
    BEGIN,
    `  // The list: National Headquarters' "Current and Past Special Activity Ribbon List", fiscal years ${list.oldest} to ${list.newest} (October through September), the file saved ${list.saved}.`,
    `  // name: as the list prints it. others: the names a record may use for it (spellings the list gets wrong, the place left off, abbreviations).`,
    `  // activity: the credit it counts for; the places of one activity share it. current: the list shows it held in ${list.newest}. years: the years the list shows it held.`,
    '  const NCSA_ACTIVITY_LIST=[',
    lines.join(',\n'),
    '  ];',
    `  ${END}`
  ].join('\n');
}

(async () => {
  const [pdfPath, flag] = process.argv.slice(2);
  if(!pdfPath){ console.error('usage: node scripts/generate-ncsa-activity-list.cjs <list.pdf> [--check]'); process.exit(2); }
  const block = build(await readList(pdfPath));
  const source = fs.readFileSync(TARGET, 'utf8');
  const at = source.indexOf('// BEGIN NCSA ACTIVITY LIST'), to = source.indexOf(END);
  if(at < 0 || to < 0) throw new Error('The BEGIN and END marks are not in member-report-rules.js.');
  const next = source.slice(0, at) + block + source.slice(to + END.length);
  if(flag === '--check'){
    if(next !== source){ console.error('member-report-rules.js does not hold what this list gives: rerun without --check.'); process.exit(1); }
    console.log('The table matches the list.');
    return;
  }
  fs.writeFileSync(TARGET, next);
  console.log(`Wrote ${block.split('\n').length - 7} activities to member-report-rules.js.`);
})().catch(e => { console.error(e.message); process.exit(1); });
