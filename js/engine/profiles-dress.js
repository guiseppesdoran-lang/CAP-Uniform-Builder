  // A point squeezed along `sq.deg` by sq.kx and across it by sq.ky, about sq.at (the transform render-svg applies to a layer with `squeeze`).
  function squeezePoint(p, sq){
    const r = sq.deg * Math.PI / 180, c = Math.cos(r), s = Math.sin(r), dx = p.x - sq.at.x, dy = p.y - sq.at.y;
    const u = (dx * c + dy * s) * sq.kx, v = (-dx * s + dy * c) * sq.ky;
    return { x: sq.at.x + u * c - v * s, y: sq.at.y + u * s + v * c };
  }
  async function messBoards(ctx, g, M, female){
    const id = g.general && ctx.has(`${M.garment}-general-officer-shoulder-boards`) ? `${M.garment}-general-officer-shoulder-boards` : `${M.garment}-officer-shoulder-boards`;
    if(!ctx.has(id)){ ctx.note(`No artwork for ${id}`); return; }
    const s = await ctx.spec(id);
    ctx.overlays = ctx.overlays || [];
    ctx.overlays.push(s);
    const { L, W } = MESS_BOARD[female ? 'female' : 'male'];
    const gradeId = g.key ? G.seniorOfficerInsignia(g, 'bullion') : null;
    for(const side of ['right', 'left']){
      const box = core.landmarkBounds(s, 'shoulder_board_' + side), frame = ctx.landmark(`rank_slot_${side}_frame`);
      if(!box || !frame || typeof frame.deg !== 'number') continue;
      const th = frame.deg * Math.PI / 180;
      const a = { x: Math.cos(th), y: Math.sin(th) };            // outer end toward the neck
      const d = a.y > 0 ? { x: a.y, y: -a.x } : { x: -a.y, y: a.x }; // across the board, downward
      if(d.y < 0){ d.x = -d.x; d.y = -d.y; }
      // The board's upper outer corner: its x is the box's outer side, its lower corner is the box's bottom.
      const A = { x: side === 'right' ? box.x : box.x + box.w, y: box.y + box.h - W * d.y };
      // The view from above is drawn level (levelFrame: long axis horizontal, button end toward the figure's centre, Doran: "the
      // top one should be horizontal in the image"): the sheet draws the board lying along the shoulder, so its overlay is turned
      // about the board's centre by the angle that lays the outer-to-neck direction `a` along the horizontal, then moved up until
      // the board's lower edge is TOP_VIEW_CLEAR above the board's highest point (its neck end). The overlay is clipped to the
      // board's box, turned and moved with it.
      const cB = { x: box.x + box.w / 2, y: box.y + box.h / 2 };
      const toNeck = a.x >= 0 ? 0 : 180;
      let turnView = toNeck - frame.deg;
      while(turnView > 180) turnView -= 360;
      while(turnView <= -180) turnView += 360;
      const top = Math.min(A.y, A.y + a.y * L);
      const lift = { x: 0, y: top - TOP_VIEW_CLEAR - W / 2 - cB.y };
      const cL = { x: cB.x + lift.x, y: cB.y + lift.y };
      const onView = p => core.rotatePoint({ x: p.x + lift.x, y: p.y + lift.y }, cL, turnView);
      const pad = 0.15;
      const clip = [{ x: box.x - pad, y: box.y - pad }, { x: box.x + box.w + pad, y: box.y - pad }, { x: box.x + box.w + pad, y: box.y + box.h + pad }, { x: box.x - pad, y: box.y + box.h + pad }].map(onView);
      // The layer is the whole overlay sheet, turned, and only its clip shows: the measurement overlay keeps clear of the board
      // that shows (`obstacle`), not of the sheet's box, which covered the whole coat and sent every label off the figure.
      ctx.layers.push({ type: 'asset', id, x: lift.x, y: lift.y, w: s.w, h: s.h, rotate: turnView, origin: cL, z: Z.epauletTop, role: 'epaulet-top', key: `epaulet-top:${side}`,
        title: `${side === 'right' ? 'Right' : 'Left'} shoulder board, seen from above`, clip, obstacle: core.polygonBounds(clip) });
      if(gradeId && ctx.has(gradeId)){
        const slot = ctx.point(`rank_slot_${side}_center`);
        const turn = boardGradeTurn(gradeId, frame.deg) + turnView;
        if(slot) await ctx.place(gradeId, { pieceAnchor: 'center', at: onView(slot), rotate: turn,
          flipX: side === 'right' && /colonel-(bullion|thread)$/.test(gradeId) && !/lieutenant/.test(gradeId), z: Z.epauletTopGrade, role: 'grade', key: 'grade:top-' + side });
      }
      // The edge-on view: the board art itself, the whole of it as drawn on the sheet (its bands, crest-less field, button and pointed neck end), squeezed onto the strip
      // (LIVE11-MASTER-1, Ethan: "top here does not match bottom. all tops must match everything on the bottom"): along the strap to EDGE_ON_COVER of its length and across it to
      // EDGE_ON_THICK, about the board's upper outer corner, so the strip keeps its upper edge on the shoulder line. The layer is squeezed in the scene frame (`squeeze`) and cut to
      // the squeezed board box.
      const T = EDGE_ON_THICK;
      const sq = { at: A, deg: Math.atan2(a.y, a.x) * 180 / Math.PI, kx: EDGE_ON_COVER, ky: T / W };
      const clipE = [{ x: box.x - pad, y: box.y - pad }, { x: box.x + box.w + pad, y: box.y - pad }, { x: box.x + box.w + pad, y: box.y + box.h + pad }, { x: box.x - pad, y: box.y + box.h + pad }].map(q => squeezePoint(q, sq));
      // `strip`: the rectangle the squeezed board fills (its centre, length, thickness and the turn of its length from the sheet's x axis), for the measurement overlay and the tests.
      const Ls = L * EDGE_ON_COVER, cS = { x: A.x + a.x * Ls / 2 + d.x * T / 2, y: A.y + a.y * Ls / 2 + d.y * T / 2 };
      ctx.layers.push({ type: 'asset', id, x: 0, y: 0, w: s.w, h: s.h, squeeze: sq, clip: clipE, z: Z.epauletLayer, role: 'epaulet-edge', key: `epaulet-edge:${side}`,
        strip: { x: cS.x - Ls / 2, y: cS.y - T / 2, w: Ls, h: T, rotate: side === 'right' ? frame.deg : frame.deg + 180, origin: cS },
        title: `${side === 'right' ? 'Right' : 'Left'} shoulder board, edge-on` });
      if(gradeId && ctx.has(gradeId)){
        const end = { x: A.x + d.x * T / 2, y: A.y + d.y * T / 2 };
        // The grade's art is turned as on the board (its width along the strap), scaled to the strip.
        const gs = await ctx.spec(gradeId);
        const turn = boardGradeTurn(gradeId, frame.deg);
        // The strip is the board seen edge-on: it keeps its length along the strap and is squeezed only across
        // it (gradeOnStrap, 67138dbc). The art turned by (turn - frame) lies with its width along the strap
        // (rel 0: the bars, whose height, their length, lies across) or across it (rel 90: eagle, leaf, stars),
        // so the extent across the strip decides one squeeze on that axis only, and the extent along the
        // strap stays true, as on the top view; it never grows (R1, R7; CAPR 39-1 4.1.1.1.1.1, 4.1.2.1.1.1).
        const rel = (turn - frame.deg) * Math.PI / 180, sn = Math.abs(Math.sin(rel)), cs = Math.abs(Math.cos(rel));
        const widthAcross = sn > cs;
        const across = widthAcross ? gs.w : gs.h, along = widthAcross ? gs.h : gs.w;
        const squeeze = Math.min(1, (T - 0.08) / across);
        const scale = widthAcross ? 1 : squeeze, scaleX = widthAcross ? squeeze : 1 / squeeze;
        // Its centre is as far from the strip's outer end as the top view's rank slot is from the board's, shortened with the strip (the Class A boards' rule, cadetBoards): the
        // two views place one piece at one distance. Without a slot, 5/8 in from the end (DAFI 36-2903 4.5.1.1.1).
        const slotPt = ctx.point(`rank_slot_${side}_center`);
        const dist = slotPt ? Math.max(GRADE_FROM_END + along / 2, ((slotPt.x - A.x) * a.x + (slotPt.y - A.y) * a.y) * sq.kx) : GRADE_FROM_END + along / 2;
        await ctx.place(gradeId, { pieceAnchor: 'center', at: { x: end.x + a.x * dist, y: end.y + a.y * dist }, rotate: side === 'left' && turn < -180 ? turn + 360 : turn, scale, scaleX,
          flipX: side === 'right' && /colonel-(bullion|thread)$/.test(gradeId) && !/lieutenant/.test(gradeId), z: Z.insignia, role: 'grade', key: `grade:edge-${side}`,
          title: `${side === 'right' ? 'Right' : 'Left'} shoulder board grade, edge-on` });
      }
    }
    seatViewsAboveOutline(ctx);
  }

